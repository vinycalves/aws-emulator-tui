#!/usr/bin/env bash
# Prepare a disposable AWS Emulator for the VHS demo.
#
#   ./scripts/demo-setup.sh          # start + seed on port 9393
#   ./scripts/demo-setup.sh --stop   # stop the demo emulator
#
# The demo uses an isolated HOME at .demo/home, so it never touches the
# emulator you use for development. The emulator binary is cached under
# ~/.cache/emutui-demo.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEMO_DIR="${REPO_ROOT}/.demo"
DEMO_HOME="${DEMO_DIR}/home"
PORT="${EMULATOR_PORT:-9393}"
ENDPOINT="https://127.0.0.1:${PORT}"
CACHE_DIR="${XDG_CACHE_HOME:-${HOME}/.cache}/emutui-demo"
PID_FILE="${DEMO_DIR}/emulator.pid"

stop() {
  if [[ -f "${PID_FILE}" ]]; then
    pid="$(cat "${PID_FILE}")"
    if kill -0 "${pid}" 2>/dev/null; then
      kill "${pid}" 2>/dev/null || true
      for _ in $(seq 1 20); do
        kill -0 "${pid}" 2>/dev/null || break
        sleep 0.25
      done
    fi
    rm -f "${PID_FILE}"
    echo "Stopped emulator on ${ENDPOINT}"
  else
    echo "No demo emulator PID file at ${PID_FILE}"
  fi
}

if [[ "${1:-}" == "--stop" ]]; then
  stop
  exit 0
fi

mkdir -p "${DEMO_DIR}" "${DEMO_HOME}" "${CACHE_DIR}"

if [[ -n "${AWS_EMULATOR_BIN:-}" && -x "${AWS_EMULATOR_BIN}" ]]; then
  BIN="${AWS_EMULATOR_BIN}"
elif [[ -x "${CACHE_DIR}/aws-emulator" ]]; then
  BIN="${CACHE_DIR}/aws-emulator"
elif command -v aws-emulator >/dev/null 2>&1; then
  BIN="$(command -v aws-emulator)"
else
  echo "aws-emulator not found; downloading the Debian package into ${CACHE_DIR}"
  command -v ar >/dev/null || {
    echo "ar is required to extract the package; install binutils or set AWS_EMULATOR_BIN" >&2
    exit 1
  }
  curl -fsSLo "${CACHE_DIR}/aws-emulator.deb" \
    "https://downloads.aws.com/aws-emulator/packages/aws-emulator/LTS/latest/aws-emulator_amd64.deb"
  rm -rf "${CACHE_DIR}/extract"
  mkdir -p "${CACHE_DIR}/extract"
  (
    cd "${CACHE_DIR}/extract"
    ar x "${CACHE_DIR}/aws-emulator.deb"
    tar xf data.tar.*
  )
  found="$(find "${CACHE_DIR}/extract" -path '*/bin/aws-emulator' -type f | head -1)"
  [[ -n "${found}" ]] || {
    echo "could not find bin/aws-emulator in the package" >&2
    exit 1
  }
  cp "${found}" "${CACHE_DIR}/aws-emulator"
  chmod +x "${CACHE_DIR}/aws-emulator"
  BIN="${CACHE_DIR}/aws-emulator"
fi

if command -v curl >/dev/null 2>&1 && curl -sk "${ENDPOINT}/__admin/health" 2>/dev/null | grep -q ok; then
  echo "Emulator already running at ${ENDPOINT}"
else
  echo "Starting AWS Emulator on ${ENDPOINT} (HOME=${DEMO_HOME})"
  HOME="${DEMO_HOME}" EMULATOR_TELEMETRY=off setsid nohup "${BIN}" \
    -t off -a on -p "${PORT}" > "${DEMO_DIR}/emulator.log" 2>&1 < /dev/null &
  echo $! > "${PID_FILE}"
  for _ in $(seq 1 60); do
    if curl -sk "${ENDPOINT}/__admin/health" 2>/dev/null | grep -q ok; then
      break
    fi
    sleep 1
  done
  if ! curl -sk "${ENDPOINT}/__admin/health" 2>/dev/null | grep -q ok; then
    echo "emulator did not become healthy; see ${DEMO_DIR}/emulator.log" >&2
    exit 1
  fi
fi

HOME="${DEMO_HOME}" EMULATOR_PORT="${PORT}" "${REPO_ROOT}/scripts/seed-demo.sh" >/dev/null

cat > "${REPO_ROOT}/demo/env.sh" <<EOF
# Generated by scripts/demo-setup.sh — do not commit.
export HOME="${DEMO_HOME}"
export AWS_EMULATOR_BIN="${BIN}"
export EMULATOR_ENDPOINT="${ENDPOINT}"
EOF

echo
echo "Demo environment ready."
echo "  endpoint: ${ENDPOINT}"
echo "  home:     ${DEMO_HOME}"
echo "  env file: demo/env.sh"
echo
echo "Render the video from the repository root:"
echo "  vhs demo/emutui.tape"
echo
echo "Stop the demo emulator with:"
echo "  ./scripts/demo-setup.sh --stop"